const LIGHT_EDITOR_THEMES = new Set<EditorThemeChoice>([
  'theseus-light',
  'github-light',
  'atom-one-light',
  'solarized-light',
])

// 设置页按深浅分组，避免十几项平铺在一张下拉里难以浏览
export const EDITOR_THEME_GROUPS = [
  {
    label: '跟随全站',
    options: EDITOR_THEME_OPTIONS.filter((option) => option.value === 'system'),
  },
  {
    label: '浅色',
    options: EDITOR_THEME_OPTIONS.filter((option) => LIGHT_EDITOR_THEMES.has(option.value)),
  },
  {
    label: '深色',
    options: EDITOR_THEME_OPTIONS.filter(
      (option) => option.value !== 'system' && !LIGHT_EDITOR_THEMES.has(option.value),
    ),
  },
]

export const isEditorThemeChoice = (value: unknown): value is EditorThemeChoice =>
  typeof value === 'string' && EDITOR_THEME_OPTIONS.some((option) => option.value === value)

export const monacoThemeName = (dark: boolean): string =>
  dark ? EDITOR_THEME_DARK : EDITOR_THEME_LIGHT

// system 时跟随全站主题：全站配色与某个编辑器主题同名时直接复用，
// 否则回退到力扣浅色/深色
export const resolveMonacoTheme = (
  choice: EditorThemeChoice,
  globalDark: boolean,
  siteTheme?: string,
): string => {
  if (choice !== 'system') return choice
  if (siteTheme && siteTheme in THEMES) return siteTheme
  return monacoThemeName(globalDark)
}

