import type { Monaco } from '@monaco-editor/loader'
import type { editor } from 'monaco-editor'

export const EDITOR_THEME_LIGHT = 'theseus-light'
export const EDITOR_THEME_DARK = 'theseus-dark'

export type EditorThemeChoice =
  | 'system'
  | 'theseus-light'
  | 'theseus-dark'
  | 'one-dark'
  | 'monokai'
  | 'dracula'
  | 'nord'
  | 'tokyo-night'
  | 'github-light'
  | 'github-dark'
  | 'atom-one-light'
  | 'solarized-light'

export interface EditorThemeOption {
  value: EditorThemeChoice
  label: string
}

export const EDITOR_THEME_OPTIONS: EditorThemeOption[] = [
  { value: 'system', label: '跟随全站主题' },
  { value: 'theseus-light', label: '力扣浅色' },
  { value: 'theseus-dark', label: '力扣深色' },
  { value: 'one-dark', label: 'One Dark' },
  { value: 'monokai', label: 'Monokai' },
  { value: 'dracula', label: 'Dracula' },
  { value: 'nord', label: 'Nord' },
  { value: 'tokyo-night', label: 'Tokyo Night' },
  { value: 'github-dark', label: 'GitHub 深色' },
  { value: 'github-light', label: 'GitHub 浅色' },
  { value: 'atom-one-light', label: 'Atom One' },
  { value: 'solarized-light', label: 'Solarized' },
]

export const isEditorThemeChoice = (value: unknown): value is EditorThemeChoice =>
  typeof value === 'string' && EDITOR_THEME_OPTIONS.some((option) => option.value === value)

export const monacoThemeName = (dark: boolean): string =>
  dark ? EDITOR_THEME_DARK : EDITOR_THEME_LIGHT

// system 时跟随全站深浅色，其余选项直接使用对应主题
export const resolveMonacoTheme = (choice: EditorThemeChoice, globalDark: boolean): string =>
  choice === 'system' ? monacoThemeName(globalDark) : choice

